const approvedCampaignCardIds: ReadonlySet<string> = new Set(APPROVED_CAMPAIGN_CARD_IDS);

export type BalanceRating = -2 | -1 | 0 | 1 | 2;

export interface CampaignAbilitySeed {
  ownerName: "Lotus" | "Alice" | "Unassigned";
  levelCategory?: string;
  magicStage?: Exclude<MagicTierKey, "cantrip">;
  magicListName?: string;
  nodeLabel?: string;
  balance?: {
    rating: BalanceRating;
    status: "Keep" | "Clarify" | "Revise" | "Major revision";
    summary: string;
  };
  card: Omit<ManagedCard, "assignedTo" | "nodeTreeId" | "nodeId">;
}

interface SeedInput {
  id: string;
  ownerName: CampaignAbilitySeed["ownerName"];
  name: string;
  family: "spell" | "skill" | "ability" | "sin";
  type: string;
  actionCost: string;
  range: string;
  duration: string;
  effect: string;
  description?: string;
  sourceType?: string;
  magicNature: string;
  costModel?: string;
  primaryCost?: string;
  uses?: string;
  requirements?: string;
  components?: string;
  componentDetails?: string;
  scaling?: string;
  origin?: string;
  passiveMode?: string;
  customFields?: Record<string, string>;
  tags?: string[];
  levelCategory?: string;
  magicStage?: CampaignAbilitySeed["magicStage"];
  magicListName?: string;
  nodeLabel?: string;
  rating: BalanceRating;
  status: NonNullable<CampaignAbilitySeed["balance"]>["status"];
  balanceSummary: string;
}

function makeSeed(input: SeedInput): CampaignAbilitySeed {
  const level = input.magicStage || input.levelCategory?.match(/\d+/)?.[0] || "";
  const customFields: Record<string, string> = {
    "Card Family": input.family,
    "Description": input.description || "",
    "Level": level,
    "Source Type": input.sourceType || "",
    "Use Profile::Magic Nature": input.magicNature,
    "Use Profile::Cost Model": input.costModel || "",
    "Use Profile::Primary Cost": input.primaryCost || "",
    "Use Profile::Uses Per Long Rest": input.uses || "",
    "Use Profile::Range": input.range,
    "Use Profile::Duration": input.duration,
    "Use Profile::Requirements": input.requirements || "",
    "Use Profile::Components": input.components || "",
    "Use Profile::Component Details": input.componentDetails || "",
    "Use Profile::Upcast / Scaling": input.scaling || "",
    "Use Profile::Origin": input.origin || "",
    "Use Profile::Passive Mode": input.passiveMode || "",
    "__editor_rules_mode": "manual",
    "__editor_import_pack": CAMPAIGN_ABILITY_PACK_VERSION,
    ...input.customFields,
  };

  const includeInBalanceReview = !approvedCampaignCardIds.has(input.id);
  if (includeInBalanceReview) {
    customFields["__editor_balance_rating"] = input.rating > 0 ? `+${input.rating}` : String(input.rating);
    customFields["__editor_balance_status"] = input.status;
    customFields["__editor_balance_summary"] = input.balanceSummary;
  }

  return {
    ownerName: input.ownerName,
    levelCategory: input.levelCategory,
    magicStage: input.magicStage,
    magicListName: input.magicListName,
    nodeLabel: input.nodeLabel,
    ...(includeInBalanceReview ? {
      balance: {
        rating: input.rating,
        status: input.status,
        summary: input.balanceSummary,
      },
    } : {}),
    card: {
      id: input.id,
      name: input.name,
      type: input.type,
      actionCost: input.actionCost,
      tags: input.tags || [],
      effect: input.effect,
      customFields,
    },
  };
}

